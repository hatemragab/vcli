import { z } from 'zod';

/** Approved event facts only; unknown fields are stripped before any destination. */
export const diagnosticInputSchema = z.object({
  event: z.enum([
    'application.starting',
    'application.started',
    'application.stopping',
    'application.stopped',
    'application.start-failed',
    'application.shutdown-failed',
    'application.start-cleanup-failed',
    'framework.log',
    'http.completed',
    'http.failed',
    'realtime.admitted',
    'realtime.denied',
    'realtime.dropped',
    'operation.completed',
    'operation.failed',
  ]),
  severity: z.enum(['debug', 'info', 'warn', 'error']),
  requestId: z.uuid().optional(),
  operationId: z.uuid().optional(),
  runId: z.uuid().optional(),
  errorCode: z
    .enum([
      'UNAUTHENTICATED',
      'AUTHORITY_UNAVAILABLE',
      'REALTIME_LIMIT',
      'INVALID_REQUEST',
      'INTERNAL_ERROR',
      'NOT_FOUND',
      'DEPENDENCY_UNAVAILABLE',
      'DIAGNOSTICS_UNAVAILABLE',
      'INVALID_REALTIME_TICKET',
      'NOTE_NOT_FOUND',
      'PAYLOAD_TOO_LARGE',
      'REQUEST_ABORTED',
      'STARTUP_FAILED',
      'SHUTDOWN_FAILED',
      'INVALID_CONFIG',
      'DATABASE_UNAVAILABLE',
      'DATABASE_URL_REQUIRED',
      'ENV_FILE_UNAVAILABLE',
      'UNSAFE_ENV_FILE',
      'INVALID_CREDENTIALS',
      'RATE_LIMITED',
      'SESSION_REVOKED',
      'SESSION_NOT_FOUND',
      'RECENT_AUTH_REQUIRED',
      'EMAIL_VERIFICATION_REQUIRED',
      'RECORD_NOT_FOUND',
      'MEDIA_NOT_FOUND',
      'MEDIA_CONFLICT',
      'STORAGE_UNAVAILABLE',
      'FIREBASE_UNAVAILABLE',
      'FIREBASE_USER_DISABLED',
      'FIREBASE_TOKEN_REVOKED',
    ])
    .optional(),
  count: z.number().int().nonnegative().max(1000000).optional(),
  durationMs: z.number().nonnegative().max(86400000).optional(),
  method: z
    .enum([
      'GET',
      'HEAD',
      'POST',
      'PUT',
      'PATCH',
      'DELETE',
      'OPTIONS',
      'CONNECT',
      'TRACE',
    ])
    .optional(),
  statusCode: z.number().int().min(100).max(599).optional(),
  route: z
    .enum([
      '/',
      '/reference',
      '/reference/config',
      '/notes',
      '/notes/:id',
      '/health/live',
      '/health/ready',
      '/accounts/me',
      '/sessions',
      '/sessions/revoke',
      '/identity/firebase/bootstrap',
      '/identity/local/register',
      '/identity/local/login',
      '/identity/local/refresh',
      '/identity/local/password/change',
      '/identity/local/verification/request',
      '/identity/local/verification/confirm',
      '/identity/local/reset/request',
      '/identity/local/reset/confirm',
      '/media',
      '/media/uploads',
      '/media/uploads/:id/content',
      '/media/uploads/:id/finalize',
      '/media/:id/content',
      '/media/:id',
      '/media/cleanup',
      '/push/destinations',
      '/push/destinations/:id',
      '/push/self',
      '/realtime/profile',
      '/realtime/tickets',
      '/realtime/centrifugo-grants',
      '/realtime/centrifugo/connect',
      '/realtime/centrifugo/refresh',
    ])
    .optional(),
});

export const diagnosticContextSchema = diagnosticInputSchema.pick({
  requestId: true,
  operationId: true,
  runId: true,
});

export type DiagnosticContext = Readonly<
  z.infer<typeof diagnosticContextSchema>
>;
