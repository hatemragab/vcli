export type DiagnosticRoute = (typeof diagnosticRoutes)[number];

const knownRoutes = new Set<string>(diagnosticRoutes);

/** Never record a raw URL. Unknown safe templates use the shared custom value. */
export function approvedRoute(value: string): DiagnosticRoute | undefined {
  if (knownRoutes.has(value)) return value as DiagnosticRoute;
  if (/^[a-z0-9/:_-]{1,80}$/.test(value)) return 'custom';
  return undefined;
}
